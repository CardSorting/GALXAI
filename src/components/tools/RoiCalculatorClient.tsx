'use client';

import React, { useState } from 'react';
import Link from 'next/link';
import { Navigation } from '@/components/dashboard/Navigation';
import { Breadcrumbs } from '@/components/common/Breadcrumbs';
import {
  Calculator,
  Sparkles,
  Copy,
  Check,
  Flame,
  Activity,
  ShieldCheck,
  ArrowRight,
  HelpCircle,
  ChevronDown,
  ChevronUp,
  DollarSign,
  TrendingUp,
  Users,
  Download,
} from 'lucide-react';
import { ShareButton } from '@/components/common/ShareButton';
import { TrustSeals } from '@/components/common/TrustSeals';
import { FloatingConversionDock } from '@/components/dashboard/FloatingConversionDock';
import { safeCopyToClipboard } from '@/lib/resilience/safeClipboard';

interface ModelOption {
  id: string;
  name: string;
  provider: string;
  inputCost1M: number;
  outputCost1M: number;
  cachedInputCost1M: number;
  retailInput1M: number;
  retailOutput1M: number;
}

const ROI_MODELS: ModelOption[] = [
  {
    id: 'gpt-5.6-sol',
    name: 'OpenAI GPT-5.6 Sol (Reasoning & Code)',
    provider: 'OpenAI',
    inputCost1M: 3.75,
    outputCost1M: 15.0,
    cachedInputCost1M: 1.25,
    retailInput1M: 5.0,
    retailOutput1M: 20.0,
  },
  {
    id: 'gpt-5.6-terra',
    name: 'OpenAI GPT-5.6 Terra (Balanced Production)',
    provider: 'OpenAI',
    inputCost1M: 2.25,
    outputCost1M: 9.0,
    cachedInputCost1M: 0.75,
    retailInput1M: 3.0,
    retailOutput1M: 12.0,
  },
  {
    id: 'gpt-5.6-luna',
    name: 'OpenAI GPT-5.6 Luna (High-Velocity)',
    provider: 'OpenAI',
    inputCost1M: 0.75,
    outputCost1M: 3.0,
    cachedInputCost1M: 0.25,
    retailInput1M: 1.0,
    retailOutput1M: 4.0,
  },
  {
    id: 'x-ai/grok-4.6',
    name: 'xAI Grok 4.6 (1M Context Flagship)',
    provider: 'xAI',
    inputCost1M: 2.8,
    outputCost1M: 11.2,
    cachedInputCost1M: 0.75,
    retailInput1M: 4.0,
    retailOutput1M: 16.0,
  },
];

export function RoiCalculatorClient() {
  const [dailyUsers, setDailyUsers] = useState<number>(10000);
  const [requestsPerUser, setRequestsPerUser] = useState<number>(8);
  const [avgPromptTokens, setAvgPromptTokens] = useState<number>(1200);
  const [avgOutputTokens, setAvgOutputTokens] = useState<number>(350);
  const [cacheHitRate, setCacheHitRate] = useState<number>(65); // 65% hit rate
  const [selectedModelId, setSelectedModelId] = useState<string>('gpt-5.6-terra');
  const [copiedReport, setCopiedReport] = useState<boolean>(false);
  const [openFaqIndex, setOpenFaqIndex] = useState<number | null>(0);

  const model = ROI_MODELS.find((m) => m.id === selectedModelId) || ROI_MODELS[1];

  // Monthly Calculations (30 days)
  const monthlyRequests = dailyUsers * requestsPerUser * 30;
  const monthlyPromptTokens = monthlyRequests * avgPromptTokens;
  const monthlyOutputTokens = monthlyRequests * avgOutputTokens;

  // Cached vs Uncached input tokens
  const cachedInputTokens = monthlyPromptTokens * (cacheHitRate / 100);
  const uncachedInputTokens = monthlyPromptTokens - cachedInputTokens;

  // Direct Retail Cost
  const retailInputSpend = (monthlyPromptTokens / 1_000_000) * model.retailInput1M;
  const retailOutputSpend = (monthlyOutputTokens / 1_000_000) * model.retailOutput1M;
  const totalRetailMonthly = retailInputSpend + retailOutputSpend;

  // GALXAI Wholesale Spend (with 75% caching discount)
  const galxaiUncachedInputSpend = (uncachedInputTokens / 1_000_000) * model.inputCost1M;
  const galxaiCachedInputSpend = (cachedInputTokens / 1_000_000) * model.cachedInputCost1M;
  const galxaiOutputSpend = (monthlyOutputTokens / 1_000_000) * model.outputCost1M;
  const totalGalxaiMonthly = galxaiUncachedInputSpend + galxaiCachedInputSpend + galxaiOutputSpend;

  const monthlyDollarSavings = Math.max(0, totalRetailMonthly - totalGalxaiMonthly);
  const annualDollarSavings = monthlyDollarSavings * 12;
  const savingsPct = totalRetailMonthly > 0 ? Math.round((monthlyDollarSavings / totalRetailMonthly) * 100) : 0;

  const reportText = `GALXAI Enterprise LLM Budget & ROI Summary:
--------------------------------------------------
Model: ${model.name}
Active Scale: ${dailyUsers.toLocaleString()} DAUs (${monthlyRequests.toLocaleString()} requests/mo)
Token Volume: ${((monthlyPromptTokens + monthlyOutputTokens) / 1_000_000).toFixed(1)}M Total Tokens/mo
Prompt Caching Hit Rate: ${cacheHitRate}%

Monthly Direct Provider List Cost: $${totalRetailMonthly.toFixed(2)}
Monthly GALXAI Wholesale Cost:     $${totalGalxaiMonthly.toFixed(2)}
--------------------------------------------------
Monthly Net Savings:               $${monthlyDollarSavings.toFixed(2)} (-${savingsPct}%)
Annual Net Savings:                $${annualDollarSavings.toFixed(2)} / year
Platform Surcharges:               $0 / month ($0 per-seat fee)
--------------------------------------------------
Generated by GALXAI ROI Engine (https://galx.ai/tools/roi-calculator)`;

  const handleCopyReport = async () => {
    const ok = await safeCopyToClipboard(reportText);
    if (ok) {
      setCopiedReport(true);
      setTimeout(() => setCopiedReport(false), 2000);
    }
  };

  return (
    <div className="min-h-screen flex flex-col">
      <Navigation />

      <main className="flex-1 max-w-6xl w-full mx-auto p-4 sm:p-6 lg:p-8 space-y-10">
        <Breadcrumbs
          items={[
            { label: 'Developer Tools', href: '/tools/model-cost-comparator' },
            { label: 'Enterprise LLM ROI & Token Budget Calculator' },
          ]}
        />

        {/* Hero Section */}
        <section id="tool-hero" className="glass-panel rounded-3xl p-6 sm:p-10 space-y-4 border border-emerald-500/20 relative overflow-hidden">
          <div className="flex flex-wrap items-center justify-between gap-3">
            <div className="inline-flex items-center gap-2 px-3 py-1 rounded-full bg-emerald-500/10 border border-emerald-500/30 text-emerald-300 text-xs font-mono font-bold">
              <DollarSign className="w-3.5 h-3.5" />
              <span>ENTERPRISE ROI &amp; BUDGET CALCULATOR</span>
            </div>
            <ShareButton
              variant="pill"
              label="Share ROI Calculator"
              title="Enterprise LLM ROI & Token Budget Calculator — GALXAI"
              description="Model token spend across DAUs, 75% prompt caching, and wholesale rates."
            />
          </div>

          <h1 className="text-3xl sm:text-4xl lg:text-5xl font-black text-white tracking-tight font-sans">
            Enterprise LLM ROI &amp; Token Budget Calculator
          </h1>
          <p className="text-sm sm:text-base text-zinc-300 leading-relaxed max-w-3xl font-sans">
            Model monthly AI inference spend for production applications. Factor in Daily Active Users (DAUs), query frequencies, compound 75% prompt caching rebates, and 25%–40% wholesale clearance rates.
          </p>

          {/* AEO Direct Answer Block */}
          <div id="aeo-direct-answer" className="p-4 rounded-2xl bg-black/60 border border-white/10 flex flex-col sm:flex-row sm:items-center justify-between gap-4 font-mono text-xs">
            <div className="space-y-1">
              <span className="text-zinc-500 block text-[10px] uppercase font-bold">AEO ROI Verdict:</span>
              <p className="text-zinc-200 font-sans text-xs">
                At <strong>{dailyUsers.toLocaleString()} DAUs</strong> on <strong>{model.name}</strong> with {cacheHitRate}% prompt caching, GALXAI saves <strong>${monthlyDollarSavings.toFixed(2)}/mo (${annualDollarSavings.toFixed(2)}/year)</strong> vs direct provider billing with <strong>$0 platform seat fees</strong>.
              </p>
            </div>
            <div className="flex items-center gap-2 text-emerald-400 font-bold shrink-0 self-start sm:self-auto">
              <Flame className="w-4 h-4 fill-emerald-400" />
              <span>{savingsPct}% Spend Reduction</span>
            </div>
          </div>
        </section>

        {/* Interactive Parameter Sliders */}
        <section id="parameter-sliders" className="grid grid-cols-1 lg:grid-cols-3 gap-6">
          <div className="lg:col-span-2 glass-panel rounded-3xl p-6 sm:p-8 space-y-6 border border-white/10">
            <div className="space-y-1 border-b border-white/10 pb-4">
              <h2 className="text-lg font-bold text-white font-sans">Application Scale &amp; Token Parameters</h2>
              <p className="text-xs text-zinc-400">Configure your production traffic patterns to calculate ROI.</p>
            </div>

            {/* Model Selection */}
            <div className="space-y-2">
              <label className="text-xs font-mono font-bold text-zinc-300 uppercase">Target Frontier Model:</label>
              <div className="grid grid-cols-1 sm:grid-cols-2 gap-2 font-mono text-xs">
                {ROI_MODELS.map((m) => (
                  <button
                    key={m.id}
                    onClick={() => setSelectedModelId(m.id)}
                    className={`p-3 rounded-xl border text-left transition-all cursor-pointer ${
                      selectedModelId === m.id
                        ? 'bg-emerald-500/10 border-emerald-400 text-white font-bold'
                        : 'bg-black/40 border-white/10 text-zinc-400 hover:text-white'
                    }`}
                  >
                    <div className="flex items-center justify-between">
                      <span className="text-xs text-white">{m.name.split(' (')[0]}</span>
                      <span className="text-[10px] text-emerald-400 font-bold">
                        -${Math.round(((m.retailOutput1M - m.outputCost1M) / m.retailOutput1M) * 100)}%
                      </span>
                    </div>
                  </button>
                ))}
              </div>
            </div>

            {/* Sliders */}
            <div className="space-y-5 font-mono text-xs">
              {/* DAUs */}
              <div className="space-y-2">
                <div className="flex justify-between">
                  <span className="text-zinc-400">Daily Active Users (DAUs):</span>
                  <span className="text-white font-bold">{dailyUsers.toLocaleString()} Users</span>
                </div>
                <input
                  type="range"
                  min="500"
                  max="100000"
                  step="500"
                  value={dailyUsers}
                  onChange={(e) => setDailyUsers(Number(e.target.value))}
                  className="w-full h-2 bg-zinc-800 rounded-lg appearance-none cursor-pointer accent-emerald-400"
                />
              </div>

              {/* Requests / User */}
              <div className="space-y-2">
                <div className="flex justify-between">
                  <span className="text-zinc-400">Queries / User / Day:</span>
                  <span className="text-white font-bold">{requestsPerUser} Queries</span>
                </div>
                <input
                  type="range"
                  min="1"
                  max="50"
                  step="1"
                  value={requestsPerUser}
                  onChange={(e) => setRequestsPerUser(Number(e.target.value))}
                  className="w-full h-2 bg-zinc-800 rounded-lg appearance-none cursor-pointer accent-emerald-400"
                />
              </div>

              {/* Prompt Tokens */}
              <div className="space-y-2">
                <div className="flex justify-between">
                  <span className="text-zinc-400">Avg. Prompt Tokens (Input):</span>
                  <span className="text-white font-bold">{avgPromptTokens.toLocaleString()} Tokens</span>
                </div>
                <input
                  type="range"
                  min="200"
                  max="10000"
                  step="100"
                  value={avgPromptTokens}
                  onChange={(e) => setAvgPromptTokens(Number(e.target.value))}
                  className="w-full h-2 bg-zinc-800 rounded-lg appearance-none cursor-pointer accent-emerald-400"
                />
              </div>

              {/* Output Tokens */}
              <div className="space-y-2">
                <div className="flex justify-between">
                  <span className="text-zinc-400">Avg. Completion Tokens (Output):</span>
                  <span className="text-white font-bold">{avgOutputTokens.toLocaleString()} Tokens</span>
                </div>
                <input
                  type="range"
                  min="50"
                  max="2000"
                  step="50"
                  value={avgOutputTokens}
                  onChange={(e) => setAvgOutputTokens(Number(e.target.value))}
                  className="w-full h-2 bg-zinc-800 rounded-lg appearance-none cursor-pointer accent-emerald-400"
                />
              </div>

              {/* Cache Hit Rate */}
              <div className="space-y-2">
                <div className="flex justify-between">
                  <span className="text-purple-300">Prompt Prefix Cache Hit Rate:</span>
                  <span className="text-purple-300 font-bold">{cacheHitRate}% (-75% on Hit)</span>
                </div>
                <input
                  type="range"
                  min="0"
                  max="95"
                  step="5"
                  value={cacheHitRate}
                  onChange={(e) => setCacheHitRate(Number(e.target.value))}
                  className="w-full h-2 bg-zinc-800 rounded-lg appearance-none cursor-pointer accent-purple-400"
                />
              </div>
            </div>
          </div>

          {/* Real-Time Financial Verdict Panel */}
          <div className="glass-panel rounded-3xl p-6 sm:p-8 space-y-6 border border-emerald-500/30 bg-emerald-500/5 flex flex-col justify-between">
            <div className="space-y-4">
              <div className="space-y-1 border-b border-white/10 pb-3">
                <span className="text-[10px] font-mono font-bold uppercase text-emerald-400 tracking-wider">
                  Monthly Financial Summary
                </span>
                <h3 className="text-lg font-black text-white">Estimated Spend &amp; Arbitrage</h3>
              </div>

              <div className="space-y-3 font-mono text-xs">
                <div className="flex justify-between p-3 rounded-xl bg-black/40 border border-white/5">
                  <span className="text-zinc-400">Direct Retail List:</span>
                  <span className="text-zinc-300 line-through">${totalRetailMonthly.toFixed(2)}</span>
                </div>

                <div className="flex justify-between p-3 rounded-xl bg-emerald-500/10 border border-emerald-500/30">
                  <span className="text-white font-bold">GALXAI Wholesale:</span>
                  <span className="text-emerald-400 font-black text-sm">${totalGalxaiMonthly.toFixed(2)}</span>
                </div>

                <div className="p-4 rounded-2xl bg-black/60 border border-emerald-500/40 text-center space-y-1">
                  <span className="text-[10px] text-zinc-400 uppercase block font-bold">Total Annual Net Savings</span>
                  <div className="text-3xl font-black text-emerald-400">${annualDollarSavings.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}</div>
                  <span className="text-[11px] text-zinc-300 font-sans block">Saves ~{savingsPct}% across {monthlyRequests.toLocaleString()} requests</span>
                </div>
              </div>
            </div>

            <div className="space-y-2 pt-4 border-t border-white/10">
              <button
                onClick={handleCopyReport}
                className="w-full py-2.5 rounded-xl bg-white/10 hover:bg-white/15 text-white font-mono text-xs font-bold border border-white/10 flex items-center justify-center gap-2 transition-all cursor-pointer"
              >
                {copiedReport ? <Check className="w-4 h-4 text-emerald-400" /> : <Copy className="w-4 h-4" />}
                <span>{copiedReport ? 'Copied Budget Report' : 'Copy Executive Budget Report'}</span>
              </button>

              <Link
                href="/keys/new"
                className="w-full py-2.5 rounded-xl bg-emerald-400 hover:bg-emerald-300 text-black font-mono text-xs font-black uppercase tracking-wider flex items-center justify-center gap-2 transition-all shadow-lg shadow-emerald-500/20"
              >
                <span>Claim $5 Free Compute Key</span>
                <ArrowRight className="w-3.5 h-3.5" />
              </Link>
            </div>
          </div>
        </section>

        {/* AEO Frequently Asked Questions */}
        <section id="faqs" className="glass-panel rounded-3xl p-6 sm:p-8 space-y-4 border border-white/10">
          <div className="space-y-1 border-b border-white/10 pb-3">
            <h2 className="text-lg font-bold text-white font-mono flex items-center gap-2">
              <HelpCircle className="w-4 h-4 text-amber-400" />
              <span>Frequently Asked Questions &amp; Token Budgeting</span>
            </h2>
            <p className="text-xs text-zinc-400">Authoritative direct answers on enterprise AI ROI and cost optimization.</p>
          </div>

          <div className="space-y-3 pt-2">
            {[
              {
                q: 'How does GALXAI achieve 25%–40% token discounts vs direct retail?',
                a: 'GALXAI aggregates enterprise compute volume to qualify for maximum tier clearance rates, passing 100% of the wholesale discount directly to developers with $0 monthly platform seat fees.',
              },
              {
                q: 'How is the 75% prompt caching discount applied in the calculator?',
                a: 'When prompt prefixes exceed 1,024 tokens and match active RAM cache slices, input pricing for the cached segment drops by 75% (e.g. from $2.25/1M to $0.75/1M on GPT-5.6 Terra).',
              },
              {
                q: 'Does GALXAI require annual volume commitments or seat fees?',
                a: 'No. GALXAI operates with $0 monthly platform fees, zero seat surcharges, and pay-as-you-go billing with complete deposit liquidity refundability.',
              },
            ].map((faq, idx) => {
              const isOpen = openFaqIndex === idx;
              return (
                <div key={idx} className="rounded-2xl bg-black/40 border border-white/10 overflow-hidden">
                  <button
                    onClick={() => setOpenFaqIndex(isOpen ? null : idx)}
                    className="w-full p-4 text-left flex items-center justify-between gap-4 cursor-pointer hover:bg-white/[0.02] transition-colors"
                  >
                    <span className="font-bold text-white text-sm font-sans">{faq.q}</span>
                    <div className="w-6 h-6 rounded-lg bg-white/5 flex items-center justify-center shrink-0 text-zinc-400">
                      {isOpen ? <ChevronUp className="w-4 h-4" /> : <ChevronDown className="w-4 h-4" />}
                    </div>
                  </button>

                  {isOpen && (
                    <div className="px-4 pb-4 pt-1 text-xs text-zinc-300 leading-relaxed border-t border-white/5 font-sans">
                      {faq.a}
                    </div>
                  )}
                </div>
              );
            })}
          </div>
        </section>

        {/* Consumer-Grade Trust Seals */}
        <TrustSeals />
      </main>

      {/* Floating Conversion Dock */}
      <FloatingConversionDock />
    </div>
  );
}
