def watched_files(root):
    return sorted({str(p.relative_to(root)) for pattern in WATCH_PATTERNS
                   for p in root.glob(pattern) if p.is_file()})


def load(root, name):
    return json.loads((root / name).read_text())


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def authored_docs(root):
    paths = set(root.glob('*.md'))
    for directory in ('docs', 'internal', 'post-mortem', 'src', 'simulations', 'tests', 'output-test'):
        paths.update((root / directory).rglob('*.md'))
    return sorted(p for p in paths if not any(part in {
        'node_modules', '.git', '.next', '__pycache__'} for part in p.relative_to(root).parts)
        and '/evidence/raw/' not in p.as_posix())


def scope(path, root):
    match = re.search(r'<!-- docs-scope: ([\w-]+) -->', path.read_text())
    if match:
        return match[1]
    rel = path.relative_to(root).as_posix()
    if rel.startswith(('internal/', 'simulations/', 'tests/', 'output-test/')):
        return 'historical-or-research-unreviewed'
    return 'supporting-reference-unreviewed'


def title(path):
    return next((line[2:].strip().replace('|', '\\|') for line in path.read_text().splitlines()
                 if line.startswith('# ')), path.stem)


def inventory(root):
    # Navigation generation is not semantic certification. Reviewed source is
    # represented separately in review.json and never updated by --sync.
    return {'version': 1, 'scope': 'repository-owned Markdown; not a semantic certification',
            'documents': [{'path': str(p.relative_to(root)), 'scope': scope(p, root),
                           'category': str(p.relative_to(root)).split('/')[0] if p.parent != root else 'root',
                           'title': title(p)} for p in authored_docs(root)]}


def cell(value):
    return str(value).replace('|', '\\|').replace('\n', ' ')


def generated_views(root, register, events):
    header = '<!-- docs-scope: current-guide -->\n\nGenerated by `npm run docs:sync`; edit the JSON register/journal, not this view.\n\n'
    incidents = '# Incident index\n\n' + header + '| Incident | Category / severity | State | Evidence |\n| --- | --- | --- | --- |\n'
    for row in register['incidents']:
        incidents += f"| {row['id']} | {row['category']} / {row['severity']} | {row['status']} | [{cell(row['title'])}]({row['record'].removeprefix('post-mortem/')}) |\n"
    actions = '# Prevention and follow-up actions\n\n' + header
    actions += 'Service recovery does not close prevention work. Dates are review deadlines, not promises of resolution. Owner roles identify responsibility; no individual assignment or scheduled automation is implied.\n\n'
    for status, label in [('open', 'Open'), ('completed', 'Completed'), ('accepted', 'Explicitly accepted')]:
        actions += f'## {label}\n\n| ID / incident | Owner / review by | Work and closure criterion |\n| --- | --- | --- |\n'
        for row in register['actions']:
            if row['status'] != status:
                continue
            actions += f"| {row['id']} / {row['incident']} | {cell(row['owner'])} / {row['review_by']} | {cell(row['next_step'])} Closure: {cell(row['closure'])} |\n"
        actions += '\n'
    journal = '# Rolling troubleshooting and containment log\n\n' + header
    journal += 'Observation times are UTC; date-only entries preserve the precision of their source. Historical imports do not imply current monitoring. Corrections append an event referencing the original ID.\n\n'
    for row in events:
        journal += f"## {row['id']} — {row['observed_at']}\n\nIncident: `{row['incident']}`. Kind: `{row['kind']}`.\n\n"
        for key in ('observation', 'action', 'result', 'next_step'):
            journal += f"**{key.replace('_', ' ').capitalize()}:** {row[key]}\n\n"
        journal += 'Evidence: ' + ', '.join(f'[{Path(p).name}]({p.removeprefix("post-mortem/") if p.startswith("post-mortem/") else "../"+p})' for p in row['evidence']) + '.\n\n'
        if row.get('supersedes'):
            journal += f"Corrects `{row['supersedes']}`; the original entry remains retained.\n\n"
    catalog = '# Complete documentation catalog\n\n<!-- docs-scope: current-guide -->\n\n'
    catalog += 'Private navigation. [Documentation policy](DOCUMENTATION_POLICY.md) defines authority. [Current state](../post-mortem/CURRENT_STATE.md), [incident operations](../post-mortem/README.md) and [workspace inventory](../post-mortem/documentation-inventory.json) distinguish active guidance from dated evidence and unreviewed references.\n\n'
    catalog += 'Generated by `npm run docs:sync` from document scope markers. Scope is not a claim of current deployment or complete semantic review. Historical records preserve observations; source-bound review applies only to the files named in `post-mortem/review.json`.\n\n'
    files = sorted((root / 'docs').rglob('*.md'))
    for category in SCOPES:
        catalog += '## ' + category.replace('-', ' ').title() + '\n\n| Document | Path |\n| --- | --- |\n'
        for p in files:
            if scope(p, root) == category:
                relative = p.relative_to(root / 'docs').as_posix()
                catalog += f'| [{title(p)}]({relative}) | `{relative}` |\n'
        catalog += '\n'
    return {name: body.rstrip() + '\n' for name, body in {
        'post-mortem/INCIDENTS.md': incidents, 'post-mortem/OPEN_ITEMS.md': actions,
        'post-mortem/ROLLING_LOG.md': journal, 'docs/CATALOG.md': catalog}.items()}


def validate_records(root, register, events):
    root = root.resolve()
    errors = []
    incidents = {row['id']: row for row in register['incidents']}
    if len(incidents) != len(register['incidents']):
        errors.append('Duplicate incident ID')
    failure_modes = (root / 'post-mortem/failure-modes/README.md').read_text()
    def evidence(paths, label):
        if not paths:
            errors.append(f'{label}: evidence is required')
        for name in paths:
            p = (root / name).resolve()
            if not p.is_relative_to(root) or not p.is_file() or '/evidence/raw/' in name:
                errors.append(f'{label}: missing, raw, or outside-workspace evidence: {name}')
    for row in incidents.values():
        if not re.fullmatch(r'INC-\d{8}-[A-Z]+', row['id']):
            errors.append(f"Invalid incident ID: {row['id']}")
        if row['status'] not in {'investigating', 'contained', 'recovered', 'closed'}:
            errors.append(f"Invalid incident status: {row['id']}")
        if row['severity'] not in {'SEV-1', 'SEV-2', 'SEV-3'} or not row['owner']:
            errors.append(f"Invalid severity/owner: {row['id']}")
        evidence([row['record']], row['id'])
        evidence(row['evidence'], row['id'])
        if row['status'] in {'recovered', 'closed'} and not row.get('recovery_evidence'):
            errors.append(f"{row['id']}: recovery evidence required")
        if row.get('recovery_evidence'):
            evidence(row['recovery_evidence'], row['id'])
        for mode in row['failure_modes']:
            if mode not in failure_modes:
                errors.append(f"{row['id']}: unknown failure mode {mode}")
    seen = set()
    for row in register['actions']:
        if row['id'] in seen or row['incident'] not in incidents:
            errors.append(f"Invalid action ID/incident: {row['id']}")
        seen.add(row['id'])
        date.fromisoformat(row['review_by'])
        if not all(row.get(k) for k in ('owner', 'next_step', 'closure')):
            errors.append(f"{row['id']}: missing ownership or closure criterion")
        if row['status'] not in {'open', 'completed', 'accepted'}:
            errors.append(f"{row['id']}: invalid action status")
        if row['status'] in {'completed', 'accepted'}:
            evidence(row.get('evidence', []), row['id'])
        if row['status'] == 'accepted' and not row.get('rationale'):
            errors.append(f"{row['id']}: accepted risk needs rationale")
        if row['status'] == 'open' and incidents.get(row['incident'], {}).get('status') == 'closed':
            errors.append(f"{row['incident']}: closed with open action {row['id']}")
    seen = set()
    allowed = {'id', 'incident', 'observed_at', 'kind', 'observation', 'action', 'result', 'next_step', 'evidence', 'supersedes'}
    for row in events:
        if set(row) - allowed:
            errors.append(f"{row.get('id')}: unexpected journal fields")
        if row['id'] in seen or row['incident'] not in incidents:
            errors.append(f"Invalid event ID/incident: {row['id']}")
        if row.get('supersedes') and row['supersedes'] not in seen:
            errors.append(f"{row['id']}: correction must reference an earlier event")
        seen.add(row['id'])
        timestamp = row['observed_at']
        if len(timestamp) == 10:
            date.fromisoformat(timestamp)
        else:
            parsed = datetime.fromisoformat(timestamp.replace('Z', '+00:00'))
            if parsed.utcoffset() is None or parsed.utcoffset().total_seconds() != 0:
                errors.append(f"{row['id']}: timestamp must be UTC")
        if row['kind'] not in {'observation', 'containment', 'recovery', 'verification', 'follow-up', 'correction'}:
            errors.append(f"{row['id']}: invalid event kind")
        if not all(row.get(k) for k in ('observation', 'action', 'result', 'next_step')):
            errors.append(f"{row['id']}: incomplete observation/action/result/next step")
        evidence(row['evidence'], row['id'])
    return errors


def validate_boundary(root):
    errors = []
    ignore = (root / '.vercelignore').read_text().splitlines()
    for name in ('/post-mortem/', '/internal/', '/docs/'):
        if name not in ignore:
            errors.append(f'.vercelignore must exclude {name}')
    docker_ignore = (root / '.dockerignore').read_text().splitlines() if (root / '.dockerignore').exists() else []
    for name in ('/post-mortem/', '/internal/', '/docs/'):
        if name not in docker_ignore:
            errors.append(f'.dockerignore must exclude {name}')
    if '/post-mortem/**/evidence/raw/' not in (root / '.gitignore').read_text().splitlines():
        errors.append('.gitignore must exclude raw incident evidence')
    for directory in ('src', 'public'):
        for p in (root / directory).rglob('*'):
            if not p.is_file() or p.suffix not in {'.ts', '.tsx', '.js', '.jsx', '.mjs', '.json', '.html', '.md', '.txt'}:
                continue
            content = p.read_text(errors='replace')
            if any(marker in content for marker in (PRIVATE_MARKER, KNOWLEDGE_MARKER)) or re.search(r'(?:from\s*|import\s*\(|require\s*\()[\'\"][^\'\"]*post-mortem/', content):
                errors.append(f'{p.relative_to(root)}: private incident content/import in runtime/public surface')
            for name in re.findall(r'(?:from\s*|import\s*(?:\(\s*)?|require\s*\(\s*)[\'\"]([^\'\"]+)', content):
                if name.startswith('.'):
                    target = (p.parent / name).resolve()
                    if any(target.is_relative_to((root / private).resolve()) for private in ('docs', 'internal', 'post-mortem')):
                        errors.append(f'{p.relative_to(root)}: private repository documentation import')
            if directory == 'public' and 'post-mortem' in str(p.relative_to(root)):
                errors.append(f'{p.relative_to(root)}: private incident path under public assets')
    return errors


def validate_append_only(root):
    base = os.environ.get('DOCS_BASE_REF', '').strip()
    if base and not re.fullmatch(r'[0-9a-fA-F]{40}', base):
        return ['DOCS_BASE_REF must be a full commit SHA from the CI event']
    # New branches have no before SHA. Scheduled/manual runs check the current
    # committed prefix; PR/push runs use the event baseline, including committed edits.
    base = base if base and set(base) != {'0'} else 'HEAD'
    previous = subprocess.run(['git', 'show', f'{base}:post-mortem/events.jsonl'],
                              cwd=root, capture_output=True, timeout=10)
    if previous.returncode != 0:
        # No committed journal exists during initial adoption.
        if b'does not exist' in previous.stderr or b'not in' in previous.stderr:
            return []
        return ['Unable to verify committed journal prefix; inspect Git history']
    current = (root / 'post-mortem/events.jsonl').read_bytes()
    return [] if current.startswith(previous.stdout) else ['Journal history changed: append a correction instead of rewriting committed events']


def validate_build(root):
    build = root / '.next'
    if not (build / 'BUILD_ID').is_file():
        return ['Production build is missing; run npm run build before the compiled-asset check']
    files = sorted((build / 'static').rglob('*.js')) + sorted((build / 'server/app').rglob('*.html'))
    if not files:
        return ['Production build contains no browser/rendered assets to inspect']
    markers = (PRIVATE_MARKER, KNOWLEDGE_MARKER, 'FM-CTRL-001', 'INC-20260913-IMAGES',
               'controller-stale-56815', 'private.galx_image_requests')
    errors = []
    for path in files:
        body = path.read_text(errors='replace')
        if any(marker in body for marker in markers):
            errors.append(f'{path.relative_to(root)}: private incident/receipt marker in public build asset')
    for path in build.rglob('*.nft.json'):
        for name in json.loads(path.read_text()).get('files', []):
            parts = [part for part in Path(name).parts if part not in {'.', '..'}]
            if parts and parts[0] in {'docs', 'internal', 'post-mortem'}:
                errors.append(f'{path.relative_to(root)}: private documentation directory included in runtime trace')
    print(f'Compiled boundary scan: {len(files)} browser/rendered assets; private markers and runtime trace paths checked.')
    return errors


def validate_review(root, review):
    root = root.resolve()
    errors = []
    if set(review.get('files', {})) != set(watched_files(root)):
        errors.append('Source review coverage stale: monitored files added, removed or missing')
    if not review.get('reviewer') or not review.get('note') or not review.get('reviewed_at'):
        errors.append('Missing source review attestation')
    for name, expected in review.get('files', {}).items():
        p = (root / name).resolve()
        if not p.is_relative_to(root) or not p.is_file() or digest(p) != expected:
            errors.append(f'Source/guide review stale: {name}')
    if not review.get('files'):
        errors.append('Source review has no files')
    return errors


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--sync', action='store_true')
    mode.add_argument('--review', action='store_true')
    mode.add_argument('--build', action='store_true')
    parser.add_argument('--reviewer')
    parser.add_argument('--note')
    args = parser.parse_args(argv)
    root = ROOT
    register = load(root, 'post-mortem/register.json')
    events = [json.loads(line) for line in (root / 'post-mortem/events.jsonl').read_text().splitlines() if line.strip()]
    errors = validate_records(root, register, events) + validate_boundary(root) + validate_append_only(root)
    review = load(root, 'post-mortem/review.json')
    if args.review:
        if not args.reviewer or not args.note:
            parser.error('--review requires --reviewer and --note after a source/guide review')
        if errors:
            print('\n'.join(errors), file=sys.stderr)
            return 1
        review.update(reviewed_at=datetime.now(timezone.utc).isoformat().replace('+00:00', 'Z'),
                      reviewer=args.reviewer, note=args.note,
                      files={name: digest(root / name) for name in watched_files(root)})
        (root / 'post-mortem/review.json').write_text(json.dumps(review, indent=2) + '\n')
        print(f'Recorded explicit source/guide review for {len(review["files"])} files; no runtime verification implied.')
        return 0
    views = generated_views(root, register, events)
    if args.sync and not errors:
        for name, body in views.items():
            (root / name).write_text(body)
        (root / 'post-mortem/documentation-inventory.json').write_text(json.dumps(inventory(root), indent=2, ensure_ascii=False) + '\n')
        print(f'Rendered {len(views)} indexes and inventoried {len(authored_docs(root))} authored Markdown files; review not changed.')
        return 0
    for name, body in views.items():
        if not (root / name).is_file() or (root / name).read_text() != body:
            errors.append(f'Generated view stale: {name}; run npm run docs:sync')
    inv = root / 'post-mortem/documentation-inventory.json'
    if not inv.exists() or load(root, str(inv.relative_to(root))) != inventory(root):
        errors.append('Documentation inventory stale; run npm run docs:sync')
    errors += validate_review(root, review)
    if args.build:
        errors += validate_build(root)
    for row in register['actions']:
        if row['status'] == 'open' and date.fromisoformat(row['review_by']) < datetime.now(timezone.utc).date():
            print(f"Review overdue: {row['id']} ({row['review_by']}, {row['owner']})")
    if errors:
        print('\n'.join(errors), file=sys.stderr)
        return 1
    print(f'Incident validation passed: {len(register["incidents"])} incidents, {len(events)} events, {len(register["actions"])} actions; inventory, references, publication boundary and source review.')
    return 0


if __name__ == '__main__':
    try:
        sys.exit(main())
    except (KeyError, ValueError, OSError) as error:
        print(f'Invalid incident documentation: {error}', file=sys.stderr)
        sys.exit(1)
